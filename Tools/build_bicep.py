"""Generate the deployable Bicep for a Sentinel analytics rule from rules/<slug>.yml.

Usage:
  python tools/build_bicep.py rules/role_assignment_created.yml

Output: Detections/<slug>.bicep (the same YAML always produces the same text).
"""
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
API_VERSION = "2022-04-01-preview"
RESOURCE_TYPE = "Microsoft.OperationalInsights/workspaces/providers/alertRules"
DEFAULT_WORKSPACE = "log-analyst-de-lab"

_IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


class Multiline(str):
    """Text rendered as a Bicep multi-line string."""


class Raw(str):
    """A Bicep expression written out as is, such as an interpolated string."""


def bicep_string(value):
    escaped = (
        value.replace("\\", "\\\\")
        .replace("'", "\\'")
        .replace("${", "\\${")
        .replace("\r", "\\r")
        .replace("\n", "\\n")
        .replace("\t", "\\t")
    )
    return f"'{escaped}'"


def render(value, level=0):
    pad = "  " * level
    if isinstance(value, Raw):
        return str(value)
    if isinstance(value, Multiline):
        return f"'''\n{value}\n'''"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, str):
        return bicep_string(value)
    if isinstance(value, list):
        if not value:
            return "[]"
        items = "\n".join(f"{pad}  {render(v, level + 1)}" for v in value)
        return f"[\n{items}\n{pad}]"
    if isinstance(value, dict):
        if not value:
            return "{}"
        lines = []
        for key, val in value.items():
            name = key if _IDENT.match(key) else bicep_string(key)
            lines.append(f"{pad}  {name}: {render(val, level + 1)}")
        return "{\n" + "\n".join(lines) + f"\n{pad}}}"
    raise TypeError(f"cannot render {type(value).__name__}")


def check_query(query):
    if "'''" in query:
        raise ValueError("query: must not contain three single quotes in a row")


def build_properties(rule):
    check_query(rule["query"])

    # 1. MITRE: two flat lists built from mitre_mapping
    tactics = [m["tactic"] for m in rule["mitre_mapping"]]
    techniques = []
    for m in rule["mitre_mapping"]:
        for t in m["techniques"]:
            if t not in techniques:
                techniques.append(t)

    # 2. Incident: detailed grouping does not exist in the YAML yet
    incident = rule["incident_configuration"]
    if incident["grouping_enabled"]:
        raise ValueError("incident_configuration.grouping_enabled: true is not supported by the generator yet")

    # 3. Entities: snake_case becomes camelCase
    entity_mappings = [
        {
            "entityType": m["entity_type"],
            "fieldMappings": [
                {"identifier": f["identifier"], "columnName": f["column_name"]}
                for f in m["field_mappings"]
            ],
        }
        for m in rule["entity_mappings"]
    ]

    props = {
        "displayName": rule["display_name"],
        "description": rule["description"],
        "enabled": rule["enabled"],
        "severity": rule["severity"],
        "query": Multiline(rule["query"].rstrip("\n")),
        "queryFrequency": rule["query_frequency"],
        "queryPeriod": rule["query_period"],
        "triggerOperator": rule["trigger_operator"],
        "triggerThreshold": rule["trigger_threshold"],
        "suppressionEnabled": rule.get("suppression_enabled", False),
        "suppressionDuration": rule.get("suppression_duration", "PT1H"),
        "tactics": tactics,
        "techniques": techniques,
        "eventGroupingSettings": {"aggregationKind": rule["event_grouping"]["aggregation_method"]},
        "incidentConfiguration": {"createIncident": incident["create_incident"]},
        "entityMappings": entity_mappings,
    }

    # 4. Optional field: only included when it has content
    if rule.get("custom_details"):
        props["customDetails"] = dict(rule["custom_details"])

    return props


def build_bicep(rule, slug, workspace=DEFAULT_WORKSPACE):
    tactics = ", ".join(m["tactic"] for m in rule["mitre_mapping"])
    header = [
        f"// GENERATED from rules/{slug}.yml by tools/build_bicep.py. Do not edit this file.",
        f"// Rule: {rule['display_name']} (version {rule['version']})",
        f"// MITRE: {tactics}",
        "// Keep the rule id fixed. A deleted rule id cannot be reused for some time.",
        "",
        f"param workspace string = {bicep_string(workspace)}",
        "",
        f"var ruleId = {bicep_string(rule['id'])}",
        "",
        "",
    ]
    resource = {
        "name": Raw("'${workspace}/Microsoft.SecurityInsights/${ruleId}'"),
        "kind": rule["kind"],
        "properties": build_properties(rule),
    }
    declaration = f"resource rule '{RESOURCE_TYPE}@{API_VERSION}' = {render(resource)}"
    return "\n".join(header) + declaration + "\n"


def main():
    rule_path = Path(sys.argv[1])
    slug = rule_path.stem
    rule = yaml.safe_load(open(rule_path, encoding="utf-8"))

    text = build_bicep(rule, slug)

    out = ROOT / "Detections" / f"{slug}.bicep"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"WROTE  Detections/{slug}.bicep")


if __name__ == "__main__":
    main()